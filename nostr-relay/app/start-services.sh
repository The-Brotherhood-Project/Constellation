#!/bin/sh

# Error handling
# set -e

# Run database migrations first
cd /nostr-relay/
echo "Running database migrations..."
python -m alembic upgrade head
if [ $? -ne 0 ]; then
    echo "Migration failed! Check database connection and alembic configuration."
    exit 1
fi
echo "Database migrations completed."

# Source the existing .env file if it exists to see if keys are already there
if [ -f "$ENV_FILE_PATH" ]; then
    echo "Checking parent .env file for existing keys..."
    # 1. grep -v '^#' removes comment lines
    # 2. grep -v '^$' removes blank lines
    # 3. sed adds 'export ' only to actual assignments
    eval "$(grep -v '^#' "$ENV_FILE_PATH" | grep -v '^$' | sed 's/^/export /')"
fi

# Inject cryptographic environment variables here
if [ -z "${SERVICE_PRIVATE_KEY:-}" ] || [ -z "${SERVICE_PUBLIC_KEY:-}" ] || [ -z "${SERVICE_DID:-}" ]; then
    echo "Cryptographic environment variables not set. Creating new keypair from UCAN service."

    UCAN_SERVICE_URL="${UCAN_SERVICE_URL:-http://localhost:7600}"
    URL="${UCAN_SERVICE_URL}/keygen"
    PAYLOAD='{}'

    RESPONSE=$(curl -s -X POST -H "Content-Type: application/json" -d "$PAYLOAD" "$URL" 2>&1) || {
        echo "Error: curl command itself failed to execute."
        exit 1
    }

    if [ -z "$RESPONSE" ] || echo "$RESPONSE" | grep -qE "Failed to connect|Could not resolve|404 Not Found"; then
        echo "Error: Network failure. UCAN service at $URL is completely unreachable."
        exit 1
    fi

    if ! command -v jq >/dev/null 2>&1; then
        echo "Error: 'jq' utility is missing."
        exit 1
    fi

    # 1. Safely extract raw JSON values using jq's @base64 or string cleaning
    # Extract strings and forcefully replace internal physical literal newlines to protect the shell syntax
    PRIVATE_KEY=$(echo "$RESPONSE" | jq -r '.privateKey' 2>/dev/null)
    PUBLIC_KEY=$(echo "$RESPONSE" | jq -r '.publicKey' 2>/dev/null)
    DID=$(echo "$RESPONSE" | jq -r '.did' 2>/dev/null)

    # 2. Check if variables are truly empty or equal to "null" using single-line string comparisons
    # Using 'case' structure in POSIX shell is 100% immune to multi-line string syntax breakage
    case "$PRIVATE_KEY" in ""|"null") echo "Error: Missing privateKey"; exit 1 ;; esac
    case "$PUBLIC_KEY" in ""|"null")  echo "Error: Missing publicKey";  exit 1 ;; esac
    case "$DID" in ""|"null")         echo "Error: Missing did";        exit 1 ;; esac

    # 3. Export variables for subsequent processes safely wrapped in double quotes
    export SERVICE_PRIVATE_KEY="$PRIVATE_KEY"
    export SERVICE_PUBLIC_KEY="$PUBLIC_KEY"
    export SERVICE_DID="$DID"

    # 4. Store the keys in the environment file if env_file_path is set
    if [ -n "$ENV_FILE_PATH" ]; then
cat << EOF >> "$ENV_FILE_PATH"
# Generated by UCAN Keygen Script
SERVICE_PRIVATE_KEY="$PRIVATE_KEY"
SERVICE_PUBLIC_KEY="$PUBLIC_KEY"
SERVICE_DID="$DID"
EOF
    fi

    echo "Successfully generated and stored service keypair."
    echo "DID: $DID"
fi

# Start backend API
echo "Starting backend API on port $PORT..."
exec uvicorn app.main:app --host 0.0.0.0 --port $PORT
