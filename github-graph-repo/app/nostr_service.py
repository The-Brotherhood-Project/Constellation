"""
Contains all the NOSTR relay communication related services, called by the main service or api
"""
import os
import time
import json
import base64
import hashlib
import urllib.request
import urllib.error
from typing import List, Dict, Optional, Tuple
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ed25519

PROTOCOL_NUMBER = 27000

def get_relay_urls() -> List[str]:
    """Retrieve list of NOSTR relay URLs from environment variables"""
    urls_str = os.getenv("NOSTR_RELAY_URLS") or os.getenv("NOSTR_RELAY_URL") or "http://localhost:10000"
    if not urls_str:
        return ["http://localhost:10000"]
    
    if urls_str.strip().startswith("["):
        try:
            return json.loads(urls_str)
        except Exception:
            pass

    return [url.strip().rstrip("/") for url in urls_str.split(",") if url.strip()]

def get_keypair() -> Tuple[ed25519.Ed25519PrivateKey, str]:
    """Retrieve Ed25519 private key and matching did:jwk identity"""

    priv_key_str = os.getenv("SERVICE_PRIVATE_KEY")
    did_str = os.getenv("SERVICE_DID")

    if priv_key_str and did_str:
        try:
            priv_key_str_clean = priv_key_str.strip().strip('"').strip("'").replace("\\n", "\n")
            # Try loading as PKCS8 PEM format (generated by UCAN service)
            if "BEGIN" in priv_key_str_clean:
                priv_key = serialization.load_pem_private_key(priv_key_str_clean.encode('utf-8'), password=None)
                if isinstance(priv_key, ed25519.Ed25519PrivateKey):
                    return priv_key, did_str

            raise ValueError("Invalid private key format, should be in PKCS8 PEM format")
        except Exception as e:
            print(f"Warning: Failed to parse SERVICE_PRIVATE_KEY env var ({e}), falling back to generated keypair")

def create_and_sign_event(kind: int, tags: Dict[str, str]) -> Dict:
    """Create a signed Nostr-like event payload"""
    priv_key, did = get_keypair()
    created_at = int(time.time())

    # Canonical serialization for event ID
    serialized = json.dumps([0, did, created_at, kind, tags], separators=(',', ':'), sort_keys=True)
    event_id = hashlib.sha256(serialized.encode('utf-8')).hexdigest()

    # Sign event ID using ed25519
    sig_bytes = priv_key.sign(event_id.encode('utf-8'))
    sig_hex = sig_bytes.hex()

    return {
        "id": event_id,
        "kind": kind,
        "did": did,
        "created_at": created_at,
        "tags": tags,
        "sig": sig_hex
    }

def broadcast_event(event_payload: Dict) -> Dict[str, bool]:
    """Broadcast Nostr event payload to all configured relay URLs"""
    relay_urls = get_relay_urls()
    results = {}

    payload_bytes = json.dumps(event_payload).encode('utf-8')

    for relay_base_url in relay_urls:
        endpoint = f"{relay_base_url.rstrip('/')}/events"
        req = urllib.request.Request(
            endpoint,
            data=payload_bytes,
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        try:
            with urllib.request.urlopen(req, timeout=5) as response:
                if response.status in (200, 201):
                    results[relay_base_url] = True
                    print(f"Successfully broadcast event {event_payload['id']} to relay {relay_base_url}")
                else:
                    results[relay_base_url] = False
                    print(f"Relay {relay_base_url} returned status {response.status}")
        except Exception as e:
            results[relay_base_url] = False
            print(f"Failed to broadcast event to relay {relay_base_url}: {e}")

    return results

def renew_manifest() -> Dict:
    """
    On startup, repo service renews kind 0 manifest to make sure relays know about this node.
    Kind 0 (PROTOCOL_NUMBER) is replaceable.
    """
    service_name = os.getenv("SERVICE_NAME", "brotherhood-github-graph-repo")
    service_url = os.getenv("SERVICE_URL") or "http://localhost:8000"
    _, did = get_keypair()

    tags = {
        "did": did,
        "url": service_url,
        "name": service_name,
        "sub_type": "s"
    }

    event_payload = create_and_sign_event(kind=PROTOCOL_NUMBER, tags=tags)
    print(f"Renewing manifest event (Kind 0) for service {service_name}...")
    broadcast_event(event_payload)
    return event_payload

def publish_resource_availability(cid: str, available: bool = True) -> Tuple[Dict, Dict]:
    """Publish Kind 1 (27001) Resource Availability event for a graph version/snapshot"""
    tags_json = {
        "did": f"did:cid:{cid}",
        "available": str(available).lower(),
        "endpoint": f"fetch/{cid}/json",
        "sub_type": "g",
        "file_type": "json"
    }
    event_payload_json = create_and_sign_event(kind=PROTOCOL_NUMBER + 1, tags=tags_json)
    broadcast_event(event_payload_json)
    
    # Publish as knw as well on the default endpoint
    # We cannot store binary on github, so we will need to fetch as json, convert, and then serve as knw
    tags_knw = {
        "did": f"did:cid:{cid}",
        "available": str(available).lower(),
        "endpoint": f"fetch/{cid}",
        "sub_type": "g",
        "file_type": "knw"
    }
    event_payload_knw = create_and_sign_event(kind=PROTOCOL_NUMBER + 1, tags=tags_knw)
    broadcast_event(event_payload_knw)
    
    return event_payload_json, event_payload_knw

def publish_project_update(graph_uuid: str, status: str) -> Dict:
    """Publish Kind 2 (27002) Project Update graph-curation event (non-replaceable)"""
    tags = {
        "did": f"did:uuid:{graph_uuid}",
        "endpoint": f"get-details/{graph_uuid}",
        "sub_type": 'gc',
        "status": status
    }
    event_payload = create_and_sign_event(kind=PROTOCOL_NUMBER + 2, tags=tags)
    broadcast_event(event_payload)
    return event_payload